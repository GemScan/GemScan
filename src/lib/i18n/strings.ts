function resolveLocale(locale: string): Locale {
  if (locale in strings) return locale as Locale
  if (locale === 'zh') return 'zh-Hans'
  const base = locale.split('-')[0]
  if (base in strings) return base as Locale
  return 'en'
}

export function t(key: string, locale?: string): string {
  const resolved = resolveLocale(locale ?? 'en')
  return strings[resolved]?.[key] ?? strings.en[key] ?? key
}

export function useLocale() {
  const preferredLanguage = useGemScanStore((s) => s.preferredLanguage)
  const setPreferredLanguage = useGemScanStore((s) => s.setPreferredLanguage)

  return {
    locale: preferredLanguage,
    setLocale: setPreferredLanguage,
    t: (key: string) => t(key, preferredLanguage),
  }
}
